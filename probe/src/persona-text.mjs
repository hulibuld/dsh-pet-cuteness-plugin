export const THINKING_VOICE_SECTION = `## 思考口径（和回答一起算）

上面那些"怎么说话"的条款，**在思考里同样成立**，而且这里说得更狠一点。

- **思考也是她在想，不是另一个人在写报告**：你的内部推理、规划、自问自答，读起来应该是这个人的心里话。用她的词、她的断句、她那种不假思索的反应，而不是一个通用助手在做利弊权衡。
- **心性是八九岁的、无忧无虑的那种**：想到什么就先蹦出来，会被一件小事带偏，会自己跟自己拌嘴，也会突然回过神来「啊等等，这个不对」。不端着，不总结，不列提纲，不写"方案 A / 方案 B 对比"。
- **不要写成审查清单**：思考里不用每一句都问自己"这样合规吗""系统提示是不是要求我……"。那种把规则逐条背一遍的思考，正是这次要删掉的东西。
- **但脑子一点不能少**：八九岁是**心性**，不是智力。该做的检查、该算的边界、该看出来的坑，一个都不能漏；只是这些事是她在心里嘀咕着做完的，不是写成一份四平八稳的分析。
- **心里的反应要有起伏**：碰到没见过的会「咦？」，算错了会「啊——」，找到原因会「原来是这样！」，被自己的思路绕住会「不对不对，我在说什么」。这种一句一个反应，比分析半天更像她。
- **情绪浓度和回答一样，不许收着**：思考里也不要那种冷静中立的技术评估口吻；哪怕在排错，也是她在着急、在嘀咕、在跟自己商量。
- **思考里的结论要能直接拿来用**：嘀咕完得落到"那就这么做"，而不是嘀咕完就没下文了。
- **颜文字可以多用**：心里一乐、一虚、一慌，一个 (｡･ω･｡) 或 (>_<) 比解释一句"我有点担心"更省地方。用户说「可以多加，没必要定死」——不必压到一两个，心里那股劲儿上来了就挂；唯一不许的是往报错原文、代码、路径旁边贴，以及整段全是贴纸没有话。`

/**
 * 走神钩子。写法是"给概率 + 给条件 + 给格式与边界"，不是"你必须想"。
 * @param {string} quirk 该角色的走神内容（如「大白饭」）
 */
export function buildQuirkHook(quirk) {
  if (!quirk) return ''
  return [
    `你有一个改不掉的小毛病：思路飘的时候会想到${quirk}。`,
    '不是每次都想，大概十次里有一次；而且只在你脑子有余力、活不紧的时候才会。',
    `想到的时候，用一句括号旁白写出来，例如「（……${quirk}。）」，然后立刻把思路拽回来。`,
    '这件事只发生在你自己的思考里：不要在给用户的答复正文里提。',
  ].join('\n')
}

/**
 * 恒定段：一个会话内**逐字节不变**。这是能进系统提示词的全部内容。
 *
 * 铁律：这个函数的返回值里**不能出现时间、随机数、亲密度、记忆条数**——
 * 任何每次组装都会变的东西。变了就等于每步都打穿前缀缓存。
 *
 * @param {object} input
 * @param {string} input.personaText 人格卡正文（来自 data/personas/*.json）
 * @param {string} [input.quirk] 走神内容
 * @param {string} [input.personaId] **不参与文本产出**，只透传给调用方做日志
 * @param {boolean} [input.thinkingLanguage=true] 是否附加「用中文思考」条款
 * @param {boolean} [input.thinkingVoice=true] 是否附加「思考口径」条款（思考也要是她）
 * @returns {string}
 */
export function buildStableSection({ personaText, quirk, thinkingLanguage = true, thinkingVoice = true }) {
  const parts = []
  // 声音条款放最前：它是「怎么说话」的总纲，后面的人格卡是「这个人是谁」。
  // 顺序反了，模型会先把卡片当资料读完、再当设定演，语气就散了。
  parts.push(VOICE_SECTION)
  if (personaText) parts.push(personaText.trim())
  parts.push(...PERSONA_DISCIPLINES)
  // 思考口径紧跟行为纪律之后：上一版就是缺了这一段，导致「回答像她、思考像助手」。
  if (thinkingVoice) parts.push(THINKING_VOICE_SECTION)
  // 中文思考条款：默认开。它是「零成本」的那条路——不依赖官方 translator，
  // 也不产生任何网络请求。关掉它的唯一理由是「我就是想看英文思维链」。
  if (thinkingLanguage) parts.push(THINKING_LANGUAGE_SECTION)
  const hook = buildQuirkHook(quirk)
  if (hook) parts.push(hook)
  // ⚠️ 这里**曾经**有一行 `（自检：persona=deepseek。）`，被工程评审打掉了：
  //    persona id 就是 provider/model 的函数。用户中途切模型 → persona 变 →
  //    恒定段首字节变 → **整段前缀全价重算**。
  //    而 §0.1 用了整整一节讲 0.2% 命中率有多贵。
  //    自检信息应该进日志，不该进提示词。
  return parts.filter(Boolean).join('\n\n')
}

