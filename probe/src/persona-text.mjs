/**
 * 段落 order 的合法落点。
 *
 * 宿主 `SECTION_ORDERS`（从 app.asar 读出，版本 0.2.1-rc.2）：
 *   HARNESS_IDENTITY: -1000
 *   DEPLOYMENT_PERSONA_PREFIX: 0
 *   PLAN_POLICY: 500
 *   ...
 * 我们的段落必须排在 persona 之后、工作指令之前 → (0, 500) 开区间。
 *
 * **读不到就返回 null，绝不兜底一个数字**：
 *   兜底不会报错，只会让人设静默压到工作指令后面去，比崩溃更难查。
 *
 * @param {(name: string) => number|undefined} getSectionOrder
 * @param {number} [offset=1] 在 persona 前缀之后偏移几格
 * @returns {number|null}
 */
export function resolvePersonaOrder(getSectionOrder, offset = 1) {
  const FLOOR = 0 // DEPLOYMENT_PERSONA_PREFIX
  const CEIL = 500 // PLAN_POLICY
  try {
    const anchor = getSectionOrder('DEPLOYMENT_PERSONA_PREFIX')
    if (typeof anchor !== 'number' || !Number.isFinite(anchor)) return null
    const next = anchor + offset
    if (!Number.isInteger(next)) return null
    if (next <= FLOOR || next >= CEIL) return null
    return next
  } catch {
    return null
  }
}

/**
 * 只给主会话挂人设，不给子代理挂。
 *
 * **三重判据，任一命中即判为非主会话**（宁严不宽）：
 *
 *   ① `header.origin === 'subagent'`
 *   ② `header.delegationDepth > 0`
 *   ③ `header.parentSession` 存在 —— **但 fork 除外**
 *
 * 判据 ③ 必须先排除 fork，否则会误伤用户主动 fork 出来的正经主会话。
 * 依据是宿主两处的写入原文（均已从 app.asar 核实，非推测）：
 *
 *   · fork（dsh-api-session-controller/lib/index.js）：
 *       `meta: { ..., parentSession: source.header.id, isSeeded: true }`
 *       —— **不写 origin，也不写 delegationDepth**。
 *
 *   · 子代理（dsh-subagent/lib/types/child-agent.js）：
 *       `{ parentSession: parentHeader.id, isSeeded, origin: 'subagent',
 *          delegationDepth: childDepth }`
 *       —— 三者齐写。
 *
 * 所以「有 parentSession」单独不足以定罪（fork 也有），
 * 「有 parentSession 且 isSeeded !== true」才是子代理的特征。
 * 子代理即使 isSeeded 为 true，也已由判据 ① 拦下。
 *
 * 读不到 header 时**不注册**（不是保守放行）：header 缺失的失败模式是
 * 「这个会话没人格」，用户几乎不会注意；而保守放行的失败模式是
 * 「代码评审子代理用诶嘿语气提 PR 意见」，那是会被截图嘲笑的。
 * 宁可不挂，也不要挂错地方。
 *
 * @param {any} agent
 * @returns {boolean}
 */
export function isMainAgent(agent) {
  try {
    const header = agent?.session?.header
    if (!header) return false

    // ① 宿主声明的子代理标记。类型原文：`readonly origin?: 'subagent'`
    if (header.origin === 'subagent') return false

    // ② 递归委派深度。类型原文：`readonly delegationDepth?: number`
    if (typeof header.delegationDepth === 'number' && header.delegationDepth > 0) return false

    // ③ 有父会话且不是 fork 播种出来的。fork 的原文写的正是 isSeeded: true。
    if (header.parentSession !== undefined && header.isSeeded !== true) return false

    return true
  } catch {
    return false
  }
}
